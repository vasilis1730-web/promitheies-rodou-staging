create or replace function public.admin_set_app_permissions(
  p_user_id uuid,
  p_can_supervise boolean
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
set row_security = off
as $$
declare
  v_before jsonb;
  v_after jsonb;
begin
  if not public.app_is_admin() then
    raise exception using errcode = '42501', message = 'Μόνο διαχειριστής μπορεί να μεταβάλει δικαιώματα εφαρμογής.';
  end if;
  if not exists (select 1 from public.profiles p where p.id = p_user_id) then
    raise exception 'Δεν βρέθηκε προφίλ για τον επιλεγμένο χρήστη.';
  end if;

  select to_jsonb(p) into v_before
  from public.user_app_permissions p
  where p.user_id = p_user_id;

  insert into public.user_app_permissions (user_id, can_supervise, updated_at, updated_by)
  values (p_user_id, coalesce(p_can_supervise, false), now(), auth.uid())
  on conflict (user_id) do update
    set can_supervise = excluded.can_supervise,
        updated_at = now(),
        updated_by = auth.uid();

  select to_jsonb(p) into v_after
  from public.user_app_permissions p
  where p.user_id = p_user_id;

  perform public.app_write_audit(
    'permissions_changed', 'user_app_permissions', p_user_id::text, null,
    'Μεταβολή ρητού δικαιώματος εποπτείας', v_before, v_after, '{}'::jsonb
  );
  return true;
end;
$$;

