create or replace function public.app_generic_audit_trigger()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
set row_security = off
as $$
declare
  v_before jsonb;
  v_after jsonb;
  v_row jsonb;
  v_id text;
  v_unit bigint;
begin
  v_before := case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) else null end;
  v_after := case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) else null end;
  v_row := coalesce(v_after, v_before, '{}'::jsonb);
  v_id := coalesce(v_row ->> 'id', v_row ->> 'user_id');
  if coalesce(v_row ->> 'municipal_unit_id', '') ~ '^[0-9]+$' then
    v_unit := (v_row ->> 'municipal_unit_id')::bigint;
  end if;

  perform public.app_write_audit(
    lower(tg_op), tg_table_name, v_id, v_unit, null,
    v_before, v_after, jsonb_build_object('source', 'row_trigger')
  );
  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

do $$
declare
  v_table text;
begin
  foreach v_table in array array[
    'materials', 'tender_overrides', 'mo_suppliers', 'mo_receivers',
    'award_group_configurations', 'award_groups', 'award_group_memberships'
  ]
  loop
    execute format('drop trigger if exists %I on public.%I', 'trg_' || v_table || '_audit', v_table);
    execute format(
      'create trigger %I after insert or update or delete on public.%I for each row execute function public.app_generic_audit_trigger()',
      'trg_' || v_table || '_audit', v_table
    );
  end loop;
end;
$$;

-- Καθαρισμός κάθε παλαιάς πολιτικής: οι PostgreSQL permissive policies
-- συνδυάζονται με OR, άρα μια ξεχασμένη παλιά πολιτική θα ακύρωνε το νέο RLS.
do $$
declare
  p record;
begin
  for p in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename = any(array[
        'profiles', 'municipal_units', 'procurement_groups', 'materials',
        'unit_requests', 'request_lines', 'saved_versions', 'locked_studies',
        'tender_overrides', 'award_group_configurations', 'award_groups',
        'award_group_memberships', 'user_app_permissions', 'app_audit_log',
        'mo_suppliers', 'mo_receivers', 'mo_contracts', 'mo_contract_items',
        'mo_orders', 'mo_order_items'
      ])
  loop
    execute format('drop policy %I on %I.%I', p.policyname, p.schemaname, p.tablename);
  end loop;
end;
$$;

do $$
declare
  v_table text;
begin
  foreach v_table in array array[
    'profiles', 'municipal_units', 'procurement_groups', 'materials',
    'unit_requests', 'request_lines', 'saved_versions', 'locked_studies',
    'tender_overrides', 'award_group_configurations', 'award_groups',
    'award_group_memberships', 'user_app_permissions', 'app_audit_log',
    'mo_suppliers', 'mo_receivers', 'mo_contracts', 'mo_contract_items',
    'mo_orders', 'mo_order_items'
  ]
  loop
    execute format('alter table public.%I enable row level security', v_table);
    execute format('revoke all on table public.%I from anon, authenticated', v_table);
  end loop;
end;
$$;

